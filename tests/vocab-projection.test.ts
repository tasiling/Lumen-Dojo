import assert from "node:assert/strict";
import * as projection from "../lib/dojo/practiceEvents/projection";
import { preserveProjection } from "../lib/dojo/practiceEvents/compatibility";
import { emptyDailyRecord, normalizeDailyRecord } from "../lib/dojo/formal";
import type { DailyRecord } from "../lib/dojo/formal";
type Fact = {id:string;practicedOn:string|null;occurredAt:string|null;standardRound:boolean};
const add = (projection as unknown as {addVocabulary?: (record:DailyRecord,fact:Fact)=>DailyRecord}).addVocabulary;
assert.equal(typeof add,"function","approved VF facts need a separate vocabulary/round projection");
const date="2026-10-01", first={id:"a".repeat(64),practicedOn:date,occurredAt:"2026-10-01T20:00:00Z",standardRound:true};
const daily=emptyDailyRecord(date);
daily.englishRhythm={touches:["input","output","transfer"],note:"keep note",vocabForgeRounds:0,updatedAt:null};
daily.evening.highlight="keep evening";
let applied=add!(daily,first);
assert.equal(applied.englishRhythm.vocabForgeRounds,1);
assert.equal(add!(applied,first).englishRhythm.vocabForgeRounds,1,"replay must not add another round");
assert.deepEqual(applied.englishRhythm.touches,["input","output","transfer","vocabulary"]);
assert.equal(applied.englishRhythm.note,"keep note");assert.equal(applied.evening.highlight,"keep evening");
const other={...first,id:"b".repeat(64),standardRound:false};
applied=add!(applied,other);
assert.equal(applied.englishRhythm.vocabForgeRounds,1,"nonstandard completed activity can add vocabulary but cannot invent a standard round");
for(let i=1;i<8;i++)applied=add!(applied,{...first,id:i.toString(16).padStart(64,"0")});
assert.equal(applied.englishRhythm.vocabForgeRounds,5,"retain existing daily display cap");
const ledger=(applied as DailyRecord & {practiceEventVocabulary:{manualRounds:number;events:Fact[]}}).practiceEventVocabulary;
assert.equal(ledger.events.filter(e=>e.standardRound).length,8,"full round provenance survives display cap");
assert.equal((normalizeDailyRecord(applied,date) as typeof applied).englishRhythm.vocabForgeRounds,5);
assert.deepEqual((normalizeDailyRecord(applied,date) as typeof applied & {practiceEventVocabulary:unknown}).practiceEventVocabulary,ledger,"normalizer must preserve server projection provenance");
const manual=emptyDailyRecord(date);manual.englishRhythm.vocabForgeRounds=4;
const combined=add!(add!(manual,first),{...first,id:"c".repeat(64)});
assert.equal(combined.englishRhythm.vocabForgeRounds,4,"manual and automatic do not blindly add");
const oldForm=emptyDailyRecord(date);oldForm.englishRhythm.note="new user note";
const protectedForm=preserveProjection("行光今日-20261001",oldForm,combined) as typeof combined;
assert.equal(protectedForm.englishRhythm.vocabForgeRounds,4);assert.ok(protectedForm.englishRhythm.touches.includes("vocabulary"));assert.equal(protectedForm.englishRhythm.note,"new user note");
assert.deepEqual((protectedForm as typeof protectedForm & {practiceEventVocabulary:unknown}).practiceEventVocabulary,(combined as typeof combined & {practiceEventVocabulary:unknown}).practiceEventVocabulary);
assert.equal((preserveProjection("行光今日-20261001",{...oldForm,practiceEventVocabulary:ledger},null) as Record<string,unknown>).practiceEventVocabulary,undefined,"caller cannot create an authoritative provenance ledger");
const explicitManual=structuredClone(protectedForm);explicitManual.englishRhythm.vocabForgeRounds=5;
const raised=preserveProjection("行光今日-20261001",explicitManual,combined,false,true) as typeof combined & {practiceEventVocabulary:{manualRounds:number}};
assert.equal(raised.practiceEventVocabulary.manualRounds,5,"current explicit daily edit can update the separate manual baseline");
assert.equal(raised.englishRhythm.vocabForgeRounds,5);
assert.throws(()=>add!(daily,{...first,practicedOn:null}),/日期/);
assert.throws(()=>add!(daily,{...first,practicedOn:"2026-10-02"}),/日期/);
console.log("PASS VF vocabulary projection: distinct standard round provenance, daily set, replay, capped display, manual max, other fields, normalized/old-form ledger protection and unknown-date rejection");
