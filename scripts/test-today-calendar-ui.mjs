import assert from 'node:assert/strict';
import {createRequire, Module} from 'node:module';
import {readFileSync} from 'node:fs';
import {resolve} from 'node:path';
import ts from 'typescript';
const require=createRequire(import.meta.url);
const file=resolve('lib/dojo/todayCalendarUi.ts');
const m=new Module(file);m.filename=file;m.paths=require.resolve.paths('react');
m._compile(ts.transpileModule(readFileSync(file,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText,file);
const {moveCalendarPeriod,calendarEditError}=m.exports;
assert.deepEqual(moveCalendarPeriod('2026-12','2026-12-31','month',1),{yearMonth:'2027-01',selectedDay:'2027-01-01'});
assert.deepEqual(moveCalendarPeriod('2028-02','2028-02-28','day',1),{yearMonth:'2028-02',selectedDay:'2028-02-29'});
assert.deepEqual(moveCalendarPeriod('2026-12','2026-12-30','week',1),{yearMonth:'2027-01',selectedDay:'2027-01-06'});
assert.deepEqual(moveCalendarPeriod('2027-01','2027-01-04','week',-1),{yearMonth:'2026-12',selectedDay:'2026-12-28'});
assert(calendarEditError({title:' ',date:'2026-10-19',startTime:'',endTime:''}));
assert(calendarEditError({title:'Appointment',date:'2026-02-30',startTime:'',endTime:''}));
assert(calendarEditError({title:'Appointment',date:'2026-10-19',startTime:'16:00',endTime:'15:00'}));
assert.equal(calendarEditError({title:'Appointment',date:'2026-10-19',startTime:'',endTime:''}),null);
console.log('today-calendar-ui: year/leap boundaries and event edit validation passed');
