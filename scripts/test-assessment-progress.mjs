import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import ts from 'typescript';
import {Module} from 'node:module';
const m=new Module('assessmentProgress');
m._compile(ts.transpileModule(readFileSync('lib/dojo/assessments/progress.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText,'assessmentProgress');
const {capabilityProgress,exampleDefinition,editLines}=m.exports;
const d={capabilityId:'cap',definitionVersion:2};
const old={capabilityId:'cap',definitionVersion:1,status:'assessed',verdict:'meets',confirmedAt:'2026-10-13'};
assert.equal(capabilityProgress(d,[old]).state,'not-started');
assert.equal(capabilityProgress(d,[old]).historicalConfirmed,1);
assert.equal(capabilityProgress(d,[{...old,definitionVersion:2,confirmedAt:null}]).state,'awaiting-review');
assert.equal(capabilityProgress(d,[{...old,definitionVersion:2,confirmedAt:null,verdict:'needs-work'}]).state,'practicing');
assert.equal(capabilityProgress(d,[{...old,definitionVersion:2}]).state,'mastered');
assert.equal(capabilityProgress(d,[{...old,capabilityId:'other',definitionVersion:2}]).state,'not-started');
const english=exampleDefinition('english','item'),academic=exampleDefinition('concept','item');
assert.equal(english.scope.languageDimension,'writing');assert.equal(academic.scope.languageDimension,'none');
english.criteria[0].description='edited';assert.notEqual(exampleDefinition('english','item').criteria[0].description,'edited');
assert.ok(!('confirmedAt' in academic));
assert.deepEqual(editLines('notes\n'),['notes','']);assert.deepEqual(editLines('notes\na'),['notes','a']);
console.log('PASS version-aware progress: independent capabilities, current rubric gate, historical confirmation retained; editable examples have no fake pass');
