import assert from 'node:assert/strict';
import {existsSync} from 'node:fs';
import {loader} from './weaving-test-harness.mjs';
assert.ok(existsSync('lib/dojo/readingKnowledge/model.ts'),'reading knowledge identity module must exist');
const load=loader();
const {contentKey,contentHref,parseRef}=load('lib/dojo/readingKnowledge/model.ts');
const a={kind:'reading_note',recordId:'11111111-1111-4111-8111-111111111111',parentBookId:'22222222-2222-4222-8222-222222222222'};
assert.notEqual(contentKey(a),contentKey({...a,parentBookId:'33333333-3333-4333-8333-333333333333'}));
assert.notEqual(contentKey(a),contentKey({...a,fragment:'reflection'}));
assert.equal(contentHref(a),`/reading/books/${a.parentBookId}?note=${a.recordId}`);
assert.throws(()=>parseRef({...a,kind:'external'}));
assert.throws(()=>parseRef({...a,parentBookId:undefined}));
assert.throws(()=>parseRef({...a,recordId:'../x'}));
console.log('PASS identity: read rounds, reflection, safe local routes, invalid refs');
const book=a.parentBookId,note=a.recordId;
const readCalls=[];
const sdk={dataSources:{query:async input=>{readCalls.push(input);return {results:[{id:book,properties:{'書名':{title:[{plain_text:'按摩'}]},'讀次':{number:1}}}],has_more:false,next_cursor:null};}},blocks:{children:{list:async input=>{assert.equal(input.block_id,book);return {results:[{id:note,type:'paragraph',paragraph:{rich_text:[{plain_text:'我的筆記'}]}}],has_more:false,next_cursor:null};}}}};
const adapters=loader({'@/lib/notion/client':{notion:()=>sdk,withNotionRateLimit:fn=>fn()}})('lib/dojo/readingKnowledge/adapters.ts');
assert.equal((await adapters.resolve(a)).text,'我的筆記');
assert.equal(await adapters.resolve({...a,parentBookId:'33333333-3333-4333-8333-333333333333'}),null);
assert.ok(readCalls.every(q=>q.page_size===20));
console.log('PASS production adapter: paged provider reads, owner book membership, foreign note excluded');
