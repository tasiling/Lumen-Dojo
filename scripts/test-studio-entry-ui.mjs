import assert from 'node:assert/strict';
import { chromium } from 'playwright';
const base = process.env.STUDIO_UI_URL || 'http://127.0.0.1:4173';
const browser = await chromium.launch({ headless: true, args: ['--no-sandbox'] });
const page = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
page.setDefaultTimeout(20000);
page.setDefaultNavigationTimeout(60000);
const button = name => page.getByRole('button', { name, exact: true });
const field = name => page.getByRole('textbox', { name, exact: true });
try {
    for (const realm of ['weaving', 'liaojie']) {
        await page.goto(base + '/' + realm);
        await page.getByRole('heading', { name: '靈感給 A，草稿給 B', exact: true }).waitFor();
        await button('整理已有草稿').click();
        await field('想修改的草稿').waitFor();
        const workURL = page.url();
        assert.match(workURL, new RegExp('/' + realm + '/works/.+\\?entry=write$'));
        assert.equal(await button('B 修改文章').getAttribute('aria-pressed'), 'true');
        const draft = '隔離驗收：一份已有草稿可直接交給 B。' + realm;
        await field('想修改的草稿').fill(draft);
        await field('我想表達的意思').fill('保留觀察，不替我推測他人的動機。');
        await page.getByRole('checkbox', { name: '允許把這段內容交給 ChatGPT 或製作工具', exact: true }).check();
        await button('複製 B 寫作指令').click();
        const promptDetails=page.locator('.studio-instruction-transfer details').first();if(!await promptDetails.evaluate(el=>el.open))await promptDetails.locator(':scope>summary').click();
        const instruction = await page.getByRole('textbox',{name:'寫作指令（可手動複製）',exact:true}).inputValue();
        assert.ok(instruction.includes(draft));
        assert.ok(instruction.includes('保留觀察，不替我推測他人的動機。'));
        assert.deepEqual((await page.getByRole('alert').allTextContents()).filter(text => text.trim()), []);
        await button('儲存草稿').click();
        await page.getByRole('status').filter({ hasText: '已保存，可以重新開啟接續' }).waitFor();
        await page.reload();
        assert.equal(await field('想修改的草稿').inputValue(), draft);
        await page.locator('summary').filter({ hasText: '起點說明與切換' }).click();
        await button('用 A 討論方向').click();
        assert.equal(page.url(), workURL);
        assert.equal(await field('想拿來寫的靈感或素材').inputValue(), draft);
        console.log('PASS native ' + realm + ': B starts without A, uses author decisions, saves and reloads; switching retains work and sources');
    }
    await page.goto(base + '/weaving');
    await button('從靈感開始寫').click();
    await field('想拿來寫的靈感或素材').fill('隔離驗收：一個還沒有完整答案的感受。');
    await page.getByRole('checkbox', { name: '允許把這段內容交給 ChatGPT 或製作工具', exact: true }).check();
    await button('複製 A 寫作指令').click();
    const aDetails=page.locator('.studio-instruction-transfer details').first();await page.getByRole('status').filter({hasText:'已複製'}).first().waitFor();if(!await aDetails.evaluate(el=>el.open))await aDetails.locator(':scope>summary').click();
    assert.ok((await page.getByRole('textbox',{name:'寫作指令（可手動複製）',exact:true}).inputValue()).includes('素材盤點，探索候選'));
    assert.deepEqual((await page.getByRole('alert').allTextContents()).filter(text => text.trim()), []);
    console.log('PASS native A generates material exploration instructions without a complete draft');
    await page.goto(base + '/liaojie/tools');
    await page.getByRole('link', { name: '開啟舊版知識鑽石與備份', exact: true }).click();
    await page.getByRole('heading', { name: '知識鑽石框架｜舊版草稿與備份', exact: true }).waitFor();
    await page.getByRole('heading', { name: '靈感給 A，草稿給 B', exact: true }).waitFor();
    await page.frameLocator('iframe').getByRole('heading', { name: '封閉知識煉金・寫作流程工具 v9', exact: true }).waitFor();
    await button('整理已有草稿').click();
    await field('想修改的草稿').waitFor();
    assert.match(page.url(), /\/liaojie\/works\/.*\?entry=write$/);
    assert.deepEqual(errors, []);
    console.log('PASS native legacy v9 boundary, import entry and same-realm new B route; no uncaught browser errors');
} finally { await browser.close(); }
