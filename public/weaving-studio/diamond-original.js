      '- 若答案偏向「機制說明」（需要把系統性原理講清楚）→ 選 SCQA金字塔原理。',
      '- 若答案偏向「真實共鳴」（讀者需要先感覺「這也是我」）→ 選 痛點→轉折→新可能。',
      '- 若答案偏向「單一主張的說服力」（只需要一個核心觀點打中讀者）→ 選 單一想法核心法。',
      '- 若這篇文章需要同時兼顧「讓讀者懂機制」「讓讀者有共鳴」「讓讀者知道下一步」三者缺一不可，不能只強化其中一段而犧牲其他段 → 選 知識鑽石2.0。',
