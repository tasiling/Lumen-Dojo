  var mode = modeValue(inputs.bMode, bModes, diamondOriginalChoices.bModes);
  var intent = inputs.intent;
  var theory = inputs.theory;
  var frameworkChoice = inputs.framework && inputs.framework !== 'auto' ? framework(inputs.framework) : 'auto';
  if (!requireField(draft)) return '';
  if (!requireField(intent)) return '';
  var theoryText = theory && theory.trim() !== ''
    ? '我已指定要使用的理論如下，請直接採用：\n' + theory
    : '我尚未指定理論，請你從候選中自行判斷並選出最合適的1-2個，並說明選擇理由。';

  var frameworkChooserBlock = [];
