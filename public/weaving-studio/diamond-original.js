    '1. 有明確理論名稱、研究者或概念名詞。',
    '2. 有可解釋機制的研究或理論。',
    '3. 能直接嫁接到草稿內容，而不是泛泛而談。',
    '',
    '每一項請用固定格式輸出：',
    '- 概念/研究名稱：',
